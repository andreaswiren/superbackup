fn scrubbed(s: &str) -> String {
    crate::redact::scrub(s).into_owned()
}

fn scrub_in_place(s: &mut String) {
    if let std::borrow::Cow::Owned(clean) = crate::redact::scrub(s) {
        *s = clean;
    }
}

fn scrub_opt(s: &mut Option<String>) {
    if let Some(v) = s {
        scrub_in_place(v);
    }
}

