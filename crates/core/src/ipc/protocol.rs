// ===========================================================================
// The Reply enum, generated so its tags cannot drift from the schema
// ===========================================================================

macro_rules! replies {
    ($( $wire:literal $variant:ident($payload:ty) $doc:literal )*) => {
        /// A successful response payload.
        ///
        /// Internally tagged: the `reply` key names the shape, and the
        /// payload struct's fields sit alongside it. Which tag a command
        /// produces is fixed and published in
        /// [`CommandSpec::reply`](super::CommandSpec::reply), so a caller can
        /// deserialise straight into the expected struct and treat anything
        /// else as a protocol violation.
        #[derive(Debug, Clone, Serialize, Deserialize)]
        #[serde(tag = "reply")]
        pub enum Reply {
            $(
                #[doc = $doc]
                #[serde(rename = $wire)]
                $variant($payload),
            )*
        }

        impl Reply {
            /// The `reply` discriminator this value serialises with.
            pub fn tag(&self) -> &'static str {
                match self { $( Reply::$variant(_) => $wire, )* }
            }
        }

        /// Compile-time map from a [`Reply`] variant to its wire tag.
        ///
        /// The command table refers to `reply_tag::Started` rather than to the
        /// string `"started"`, so the schema's `reply` field and the enum's
        /// serde rename are the same token. Renaming one without the other is
        /// a compile error.
        #[doc(hidden)]
        #[allow(non_upper_case_globals)]
        pub mod reply_tag {
            $( pub const $variant: &str = $wire; )*
        }

        fn reply_specs() -> Vec<ReplySpec> {
            vec![ $( ReplySpec {
                name: $wire.to_string(),
                payload: stringify!($payload).to_string(),
                summary: $doc.trim().to_string(),
            }, )* ]
        }
    };
}

