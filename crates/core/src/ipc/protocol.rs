/// A line sent by a client.
#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(tag = "type", rename_all = "snake_case")]
pub enum ClientFrame {
    /// Ask the daemon to do something.
    Request {
        /// Unique among this connection's outstanding requests.
        id: RequestId,
        /// Protocol version the client speaks. Defaults to the version this
        /// build was compiled against when omitted, so a hand-typed line
        /// stays short; a real client should send it explicitly.
        #[serde(default = "default_protocol")]
        protocol: u32,
        body: Request,
    },
    /// End a subscription opened by an earlier `subscribe` with this id.
    ///
    /// Cancelling an id that is not a live subscription is not an error: it is
    /// the natural outcome of a race between the client cancelling and the
    /// stream ending on its own.
    Cancel { id: RequestId },
}

fn default_protocol() -> u32 {
    PROTOCOL_VERSION
}

/// A line sent by the daemon.
#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(tag = "type", rename_all = "snake_case")]
pub enum ServerFrame {
    /// Sent unprompted, immediately on accept, before the client speaks.
    ///
    /// A client compares its own version against `[min_protocol, protocol]`
    /// and gives up with a clear message if it falls outside — *before* it has
    /// sent a passphrase or a destructive command to a daemon it does not
    /// understand.
    Hello {
        protocol: u32,
        min_protocol: u32,
        version: String,
        /// True when this is the machine-wide service instance. A client can
        /// use it to explain which daemon it is talking to when both a tray
        /// and a service are installed.
        service_scope: bool,
    },
    /// A request succeeded.
    Ok { id: RequestId, body: Box<Reply> },
    /// A request failed. `id` is `0` for a failure that could not be
    /// attributed to a request — an unparseable line, a rate-limit rejection
    /// before the id was read.
    Error { id: RequestId, body: ErrorPayload },
    /// One item of a subscription.
    Stream { id: RequestId, body: Box<StreamItem> },
    /// A subscription ended: the client cancelled, or the daemon is shutting
    /// down. No further frames will carry this id.
    End { id: RequestId },
    /// The daemon is closing this connection. Sent on graceful shutdown so a
    /// client can say "the service stopped" rather than "the pipe broke".
    Bye { reason: String },
}

impl ServerFrame {
    /// Run [`crate::redact::scrub`] over every field that can carry
    /// third-party text.
    ///
    /// The transport calls this on every outbound frame, so redaction is a
    /// property of the socket rather than a discipline each handler has to
    /// remember. Handlers that already scrubbed lose nothing: `scrub` is
    /// idempotent.
    pub fn sanitise(mut self) -> ServerFrame {
        match &mut self {
            ServerFrame::Ok { body, .. } => body.sanitise(),
            ServerFrame::Stream { body, .. } => body.sanitise(),
            ServerFrame::Error { body, .. } => {
                scrub_in_place(&mut body.message);
                scrub_opt(&mut body.hint);
                scrub_opt(&mut body.detail);
            }
            ServerFrame::Bye { reason } => scrub_in_place(reason),
            // Nothing but ids and version numbers this process authored.
            ServerFrame::Hello { .. } | ServerFrame::End { .. } => {}
        }
        self
    }

    /// Convenience for the transport: an error frame from a core error.
    pub fn error(id: RequestId, error: &Error) -> ServerFrame {
        ServerFrame::Error { id, body: ErrorPayload::from_error(error) }
    }
}

/// Check a client's protocol version against what this build speaks.
///
/// Returns a [`ErrorCode::Ipc`] error naming both sides, because "protocol
/// mismatch" on its own sends a user hunting through logs while "client speaks
/// 3, this daemon speaks 1..=1, upgrade the daemon" tells them what to do.
pub fn check_protocol(client: u32) -> Result<()> {
    if client < MIN_PROTOCOL_VERSION {
        return Err(Error::Ipc(format!(
            "client speaks IPC protocol {client}, which this daemon (protocol \
             {MIN_PROTOCOL_VERSION}..={PROTOCOL_VERSION}) no longer supports; upgrade the client"
        )));
    }
    if client > PROTOCOL_VERSION {
        return Err(Error::Ipc(format!(
            "client speaks IPC protocol {client}, which is newer than this daemon \
             (protocol {MIN_PROTOCOL_VERSION}..={PROTOCOL_VERSION}); upgrade the daemon"
        )));
    }
    Ok(())
}
