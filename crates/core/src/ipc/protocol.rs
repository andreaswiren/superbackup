impl Reply {
    /// Scrub every field that can carry third-party text.
    ///
    /// Called by the transport on the way out, so a handler cannot forget.
    pub fn sanitise(&mut self) {
        match self {
            Reply::Status(r) => {
                for run in &mut r.snapshot.active_runs {
                    sanitise_run(run);
                }
                for event in &mut r.snapshot.recent_events {
                    scrub_in_place(&mut event.message);
                }
            }
            Reply::Health(r) => {
                scrub_in_place(&mut r.summary);
                for reason in &mut r.reasons {
                    scrub_in_place(reason);
                }
            }
            Reply::Doctor(r) => {
                for check in &mut r.checks {
                    scrub_opt(&mut check.detail);
                    scrub_opt(&mut check.hint);
                }
            }
            Reply::Runs(r) => {
                for run in &mut r.runs {
                    sanitise_run(run);
                }
            }
            Reply::Started(r) => scrub_opt(&mut r.note),
            Reply::Probe(r) => scrub_opt(&mut r.detail),
            Reply::RemoteStatus(r) => {
                scrub_opt(&mut r.detail);
                scrub_opt(&mut r.url);
            }
            Reply::RemoteDiff(r) => {
                for change in &mut r.changes {
                    scrub_in_place(&mut change.summary);
                }
            }
            Reply::Service(r) => scrub_opt(&mut r.detail),
            // The rest carry only values this process authored: ids, counts,
            // timestamps, and configuration the user typed themselves.
            _ => {}
        }
    }
}

