/// A failure, in a form a caller can branch on.
///
/// `code` is the contract. `message` and `hint` are prose for a human and may
/// change between releases; `detail` is third-party output (kopia's stderr, a
/// git transport error) and is scrubbed before it is sent.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct ErrorPayload {
    pub code: ErrorCode,
    pub message: String,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub hint: Option<String>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub detail: Option<String>,
}

impl ErrorPayload {
    /// Build a payload from a core error, scrubbing every string.
    pub fn from_error(error: &Error) -> ErrorPayload {
        ErrorPayload {
            code: error.code(),
            message: scrubbed(&error.to_string()),
            hint: error.hint().map(scrubbed),
            detail: None,
        }
    }

    /// Build a payload directly, for transport-level failures that have no
    /// [`Error`] behind them (a malformed line, a rate-limit rejection).
    pub fn new(code: ErrorCode, message: impl AsRef<str>) -> ErrorPayload {
        ErrorPayload { code, message: scrubbed(message.as_ref()), hint: None, detail: None }
    }

    /// Attach an actionable hint.
    pub fn with_hint(mut self, hint: impl AsRef<str>) -> ErrorPayload {
        self.hint = Some(scrubbed(hint.as_ref()));
        self
    }

    /// Attach scrubbed third-party detail.
    pub fn with_detail(mut self, detail: impl AsRef<str>) -> ErrorPayload {
        self.detail = Some(scrubbed(detail.as_ref()));
        self
    }

    /// Convert back into a core [`Error`], for a client that wants to bubble
    /// the daemon's failure through its own `Result` chain.
    ///
    /// The mapping is lossy on purpose: [`Error`] carries structured fields
    /// (`std::io::Error`, exit statuses) that do not survive JSON, so
    /// everything that is not a distinguished variant becomes the closest
    /// string-carrying one. `code` is preserved exactly, which is what callers
    /// are told to branch on.
    pub fn into_error(self) -> Error {
        match self.code {
            ErrorCode::Locked => Error::Locked,
            ErrorCode::BadPassphrase => Error::BadPassphrase,
            ErrorCode::KopiaMissing => Error::KopiaMissing,
            ErrorCode::DaemonUnreachable => Error::DaemonUnreachable,
            ErrorCode::Config => Error::Config(self.message),
            ErrorCode::VaultCorrupt => Error::VaultCorrupt(self.message),
            ErrorCode::Crypto => Error::Crypto(self.message),
            ErrorCode::RepoNotConnected => Error::RepoNotConnected(self.message),
            ErrorCode::RepoExists => Error::RepoExists(self.message),
            ErrorCode::Schedule => Error::Schedule(self.message),
            ErrorCode::JobNotFound => Error::JobNotFound(self.message),
            ErrorCode::JobRunning => Error::JobRunning(self.message),
            ErrorCode::JobCancelled => Error::JobCancelled(self.message),
            ErrorCode::Service => Error::Service(self.message),
            ErrorCode::Platform => Error::Platform(self.message),
            ErrorCode::Remote => Error::Remote(self.message),
            ErrorCode::Validation => Error::Validation(self.message),
            ErrorCode::Ipc => Error::Ipc(self.message),
            // `Io`, `VaultVersion`, `Kopia` and `Internal` carry fields that
            // cannot be reconstructed; keep the prose and the code.
            _ => Error::Internal(self.message),
        }
    }
}

