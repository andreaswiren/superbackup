/// Behavioural flags published in the schema.
///
/// Referred to by identifier from the command table, so a typo is a compile
/// error rather than a silently wrong schema.
#[doc(hidden)]
#[allow(non_upper_case_globals)]
pub mod flag {
    /// Changes persistent state — configuration, the vault, or the
    /// repository. A read-only client (a dashboard, a cautious agent) should
    /// refuse to issue these.
    pub const mutating: &str = "mutating";

    /// Fails with [`ErrorCode::Locked`](crate::error::ErrorCode::Locked)
    /// while the vault is locked, because it needs a secret the vault holds.
    /// Unlock first with `vault.unlock`.
    pub const needs_unlock: &str = "needs_unlock";

    /// Causes the daemon to act with whatever privilege it happens to be
    /// running as, which for the service instance is SYSTEM or root.
    ///
    /// Every command carrying this flag must be authorised by something the
    /// caller *knows* (the vault passphrase) or by a policy the daemon holds,
    /// never by the caller's identity alone — the endpoint's access control
    /// establishes only that the peer is a local user, not that the peer is
    /// entitled to act as SYSTEM. Concretely: nothing here takes a path or a
    /// command line from the caller and executes it with elevated privilege;
    /// paths come from the stored configuration, and changing that
    /// configuration is itself gated.
    pub const elevated: &str = "elevated";

    /// Opens a stream on the request id instead of producing a single
    /// response. Handled by the transport, not by a [`Handler`](super::Handler)
    /// method.
    pub const streaming: &str = "streaming";

    /// Runs a password-based key derivation, which by design costs hundreds of
    /// megabytes and hundreds of milliseconds.
    ///
    /// The transport treats these specially: at most
    /// [`MAX_CONCURRENT_KDF`](crate::ipc::MAX_CONCURRENT_KDF) run in the whole
    /// process, at most one per connection, and a failure holds the connection
    /// for [`KDF_FAILURE_DELAY`](crate::ipc::KDF_FAILURE_DELAY) before it is
    /// answered. Without that, `max_inflight` x `max_connections` derivations
    /// at 256 MiB each is an out-of-memory kill of a process that may be
    /// running as SYSTEM, reachable by any local user who can open the socket.
    ///
    /// Put this on every handler that verifies or changes a passphrase.
    pub const kdf: &str = "kdf";
}

