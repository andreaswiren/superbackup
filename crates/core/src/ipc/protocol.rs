/// Generates, from one table:
///
/// 1. the [`Request`] enum and its serde representation,
/// 2. [`Request::command`],
/// 3. the [`Handler`] trait the daemon implements,
/// 4. [`dispatch`], which routes a request to a handler method, and
/// 5. the machine-readable [`Schema`].
///
/// Because all five come from the same tokens, they cannot disagree. Adding a
/// command is a five-line edit in one place; forgetting to wire it up anywhere
/// is impossible.
///
/// Two sections:
///
/// * `dispatched` — commands the daemon answers. Each names the [`Handler`]
///   method it routes to.
/// * `manual` — commands the *transport* answers without troubling the
///   daemon: `schema`, which is generated in-process, and `subscribe`, which
///   is a stream rather than a response. They still appear in [`Request`] and
///   in the schema; they simply have no handler method.
macro_rules! protocol {
    (
        dispatched {
            $(
                $wire:literal $variant:ident => $method:ident -> $rvar:ident($rty:ty)
                flags [$($flag:ident),* $(,)?]
                doc $doc:literal
                params { $( $pname:ident : $pty:ty = $pdoc:literal ),* $(,)? }
            )*
        }
        manual {
            $(
                $mwire:literal $mvariant:ident -> $mrvar:ident
                flags [$($mflag:ident),* $(,)?]
                doc $mdoc:literal
                params { $( $mpname:ident : $mpty:ty = $mpdoc:literal ),* $(,)? }
            )*
        }
    ) => {
        /// Everything a client can ask the daemon to do.
        ///
        /// Internally tagged on `cmd`, with parameters flat alongside it:
        /// `{"cmd":"job.run","job":"docs","dry_run":false}`.
        ///
        /// `Debug` is safe to log: secret parameters are
        /// [`SecretString`], whose `Debug` redacts.
        #[derive(Debug, Clone, Serialize, Deserialize)]
        #[serde(tag = "cmd")]
        pub enum Request {
            $(
                #[doc = $doc]
                #[serde(rename = $wire)]
                $variant { $( #[doc = $pdoc] $pname: $pty, )* },
            )*
            $(
                #[doc = $mdoc]
                #[serde(rename = $mwire)]
                $mvariant { $( #[doc = $mpdoc] $mpname: $mpty, )* },
            )*
        }

        impl Request {
            /// The wire value of this request's `cmd` field.
            ///
            /// Useful for logging and for correlating a request with its
            /// [`CommandSpec`].
            pub fn command(&self) -> &'static str {
                match self {
                    $( Request::$variant { .. } => $wire, )*
                    $( Request::$mvariant { .. } => $mwire, )*
                }
            }

            /// The behavioural flags this command carries, from the same
            /// table that fills the schema.
            ///
            /// Constant-time and allocation-free, unlike [`Request::spec`],
            /// because the transport consults it on every request to decide
            /// whether the command needs the key-derivation gate.
            pub fn flags(&self) -> &'static [&'static str] {
                match self {
                    $( Request::$variant { .. } => &[ $( flag::$flag ),* ], )*
                    $( Request::$mvariant { .. } => &[ $( flag::$mflag ),* ], )*
                }
            }

            /// True when this command runs a password-based key derivation and
            /// must therefore go through the transport's KDF gate. See
            /// [`flag::kdf`].
            pub fn is_kdf(&self) -> bool {
                self.flags().contains(&flag::kdf)
            }

            /// The specification for this request's command.
            ///
            /// Builds the whole schema and searches it, so this is for
            /// diagnostics and for a CLI's help output, not for a hot path.
            /// `None` is unreachable in practice and would mean the generated
            /// schema had lost a command it also generated.
            pub fn spec(&self) -> Option<CommandSpec> {
                let name = self.command();
                commands().into_iter().find(|c| c.name == name)
            }
        }

        /// What the daemon implements to serve IPC.
        ///
        /// One method per command, generated from the same table as
        /// [`Request`], so a new command is a compile error until the daemon
        /// handles it. That is the point: an IPC surface that silently answers
        /// `unimplemented` is worse than one that will not build.
        ///
        /// Deliberately expressed in terms of [`crate::model`],
        /// [`crate::state`] and this module's own types only. The engine, the
        /// kopia driver, the vault and the configuration loader are *not*
        /// referenced, so the transport compiles and is testable
        /// independently of them.
        ///
        /// Methods return [`Result`]; an `Err` becomes an `error` frame with
        /// the error's [`ErrorCode`]. Returning an error is the normal way to
        /// refuse — panicking is not, and the transport treats a panicking
        /// handler as a failed request rather than letting it take the daemon
        /// down.
        ///
        /// ## Running as a service
        ///
        /// The daemon may run as SYSTEM or root while its clients are
        /// unprivileged. Implementations must therefore authorise on what the
        /// caller *knows*, not on the fact that it reached the socket:
        /// anything touching secrets requires an unlocked vault, and the vault
        /// is unlocked only by presenting the passphrase. Commands whose
        /// schema entry carries the `elevated` flag are the ones where this
        /// matters most.
        #[allow(clippy::too_many_arguments)]
        pub trait Handler: Send + Sync + 'static {
            $(
                #[doc = $doc]
                $(
                    #[doc = ""]
                    #[doc = concat!("* `", stringify!($pname), "` — ", $pdoc)]
                )*
                fn $method(
                    &self,
                    ctx: &RequestContext,
                    $( $pname: $pty, )*
                ) -> impl ::std::future::Future<Output = Result<$rty>> + Send;
            )*

            /// The daemon's event fan-out, one receiver per subscription.
            ///
            /// Not generated from the command table because `subscribe` is a
            /// stream rather than a request/response pair.
            ///
            /// Must be a *broadcast* channel: it gives drop-oldest semantics
            /// for free, which is exactly the required backpressure policy. A
            /// subscriber that falls behind sees
            /// [`RecvError::Lagged`](tokio::sync::broadcast::error::RecvError::Lagged),
            /// which the transport turns into
            /// [`StreamItem::Lagged`]. Producing an item must never block on
            /// a slow consumer, and with `broadcast::Sender::send` it does
            /// not.
            fn event_stream(
                &self,
                ctx: &RequestContext,
                topics: &[Topic],
            ) -> Result<::tokio::sync::broadcast::Receiver<StreamItem>>;
        }

        /// Route one request to the handler method the table names for it.
        ///
        /// The `manual` commands never reach here; the transport intercepts
        /// them. Reaching this arm means the transport has a bug, so it
        /// reports one rather than pretending.
        pub async fn dispatch<H: Handler>(
            handler: &H,
            ctx: &RequestContext,
            request: Request,
        ) -> Result<Reply> {
            match request {
                $(
                    Request::$variant { $( $pname, )* } => handler
                        .$method(ctx, $( $pname, )*)
                        .await
                        .map(Reply::$rvar),
                )*
                $(
                    Request::$mvariant { .. } => Err(Error::Ipc(format!(
                        "`{}` is answered by the IPC transport and must not reach the dispatcher",
                        $mwire
                    ))),
                )*
            }
        }

        /// Every command, in table order.
        pub fn commands() -> Vec<CommandSpec> {
            vec![
                $(
                    CommandSpec {
                        name: $wire.to_string(),
                        summary: $doc.trim().to_string(),
                        params: vec![ $( param(stringify!($pname), stringify!($pty), $pdoc) ),* ],
                        reply: reply_tag::$rvar.to_string(),
                        flags: vec![ $( flag::$flag.to_string() ),* ],
                    },
                )*
                $(
                    CommandSpec {
                        name: $mwire.to_string(),
                        summary: $mdoc.trim().to_string(),
                        params: vec![ $( param(stringify!($mpname), stringify!($mpty), $mpdoc) ),* ],
                        reply: reply_tag::$mrvar.to_string(),
                        flags: vec![ $( flag::$mflag.to_string() ),* ],
                    },
                )*
            ]
        }
    };
}

