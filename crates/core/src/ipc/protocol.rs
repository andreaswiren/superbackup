//! The superbackup IPC wire contract.
//!
//! This module is the specification. A client in any language that can open a
//! named pipe (Windows) or a unix socket, write a line of JSON and read a line
//! of JSON can drive the daemon completely, using nothing but this file.
//!
//! # Framing
//!
//! Newline-delimited JSON. One JSON object per line, UTF-8, terminated by a
//! single `\n`. No length prefix, no envelope framing, no binary. `\r\n` is
//! tolerated on input. This costs a little parsing speed and buys a protocol
//! that can be exercised from a terminal, logged verbatim, and diffed in a bug
//! report — which for an IPC surface that humans and agents both drive is the
//! better trade.
//!
//! Lines longer than [`Limits::max_line_bytes`](super::Limits::max_line_bytes)
//! are refused; see [Denial of service](#denial-of-service).
//!
//! # Conversation
//!
//! ```text
//! server → {"type":"hello","protocol":1,"min_protocol":1,"version":"0.1.0", ...}
//! client → {"type":"request","id":1,"protocol":1,"body":{"cmd":"status"}}
//! server → {"type":"ok","id":1,"body":{"reply":"status","snapshot":{...}}}
//! client → {"type":"request","id":2,"protocol":1,"body":{"cmd":"subscribe","topics":["progress"]}}
//! server → {"type":"ok","id":2,"body":{"reply":"subscribed","subscription":2,"topics":["progress"]}}
//! server → {"type":"stream","id":2,"body":{"kind":"progress", ...}}
//! server → {"type":"stream","id":2,"body":{"kind":"progress", ...}}
//! client → {"type":"cancel","id":2}
//! server → {"type":"end","id":2}
//! ```
//!
//! The server sends [`ServerFrame::Hello`] unprompted, immediately on accept,
//! before the client says anything. That makes version negotiation a property
//! of the connection rather than of the first request: a client that cannot
//! speak the daemon's protocol learns so before it has sent a passphrase or a
//! destructive command.
//!
//! Every request carries a client-chosen `id`. Responses, stream items and the
//! terminating `end` all echo it. Ids are scoped to one connection and only
//! need to be unique among that connection's *outstanding* requests; reusing
//! an id whose response has already arrived is legal, and monotonic counting
//! is the obvious implementation. Requests may be pipelined and the daemon may
//! answer them out of order, which is precisely why the id exists.
//!
//! # Requests
//!
//! [`Request`] is internally tagged: `{"cmd":"job.run","job":"docs","dry_run":false}`.
//! The command name and its parameters live in one flat object, so a request
//! can be typed by hand. Command names are dotted (`job.run`, `vault.unlock`)
//! purely to group the surface for humans and for shell completion; the
//! dispatcher treats the whole string as one opaque key.
//!
//! # Responses
//!
//! Exactly one of:
//!
//! * `{"type":"ok","id":N,"body":{"reply":"<tag>", ...}}` — a typed
//!   [`Reply`]. The `reply` tag tells the caller which payload shape follows,
//!   and [`CommandSpec::reply`](super::CommandSpec::reply) says in advance
//!   which tag a given command produces.
//! * `{"type":"error","id":N,"body":{"code":"locked","message":"...","hint":"..."}}`
//!   — an [`ErrorPayload`]. `code` is a [`crate::error::ErrorCode`], a closed
//!   set that a caller can exhaustively branch on. `message` and `hint` are
//!   for humans and are not stable.
//!
//! A caller must never parse `message`. That is what `code` is for.
//!
//! # Discovery
//!
//! `{"cmd":"schema"}` returns [`Schema`]: every command, its
//! parameters, their types, one-line descriptions, and behavioural flags. It
//! is generated by the same macro invocation that generates [`Request`], the
//! [`Handler`] trait and the dispatcher, so it cannot describe a command that
//! does not exist or omit one that does.
//!
//! # Secrets
//!
//! Two rules, both load-bearing.
//!
//! **Secrets go in, never out.** There is deliberately no `GetSecret`. The
//! daemon can be asked to *store* a secret ([`Request::VaultSetSecret`]) and
//! to *use* one, but there is no request that returns plaintext credential
//! material, and none will be added. The consequences are worth stating
//! plainly:
//!
//! * A GUI cannot show the user their own S3 secret key. That is intentional.
//!   Reading it back is not a feature the user needs and it is the single
//!   most valuable thing an attacker who reaches the socket could ask for.
//! * Anything that needs a secret — kopia, a git transport, an S3 request —
//!   is invoked *by the daemon*, which passes the secret through the child
//!   process environment or stdin. The secret never crosses the IPC boundary
//!   in that direction.
//! * The vault file itself is sealed and is the supported way to move secrets
//!   between machines. Exporting is an explicit, passphrase-gated file
//!   operation, not an IPC call.
//!
//! **Secrets that come in are typed as secrets.** Passphrases and keys are
//! [`SecretString`], which deserialises straight into [`crate::secret::Secret`]
//! (zeroed on drop, redacting `Debug`) rather than into a `String` that could
//! be logged, cloned into a trace span, or included in a panic message. See
//! [`SecretString`] for the residue that this does *not* eliminate.
//!
//! # Redaction
//!
//! Every outbound frame passes through [`ServerFrame::sanitise`], which runs
//! [`crate::redact::scrub`] over every field that can carry third-party text:
//! error messages and details, event messages, current paths, kopia and git
//! transport output. This is the last line of defence; the first is that
//! secrets live in [`crate::secret::Secret`] and are handed to child processes
//! out of band.
//!
//! # Denial of service
//!
//! The daemon may run as a system service. A local socket is a privilege
//! boundary, and the peer is not assumed to be friendly:
//!
//! * a line over the cap is not buffered and not truncated — the connection is
//!   closed, because a peer that sends one is broken or hostile;
//! * requests are rate limited per connection;
//! * concurrent connections are capped;
//! * a slow subscriber is disconnected from the event firehose by dropping the
//!   oldest items and telling it how many it missed, never by buffering
//!   without bound and never by blocking the engine.
//!
//! The published values are in [`Schema::limits`](super::Schema::limits) so a
//! well-behaved client can stay inside them rather than discovering them by
//! being hung up on.

