/// One item of a `subscribe` stream.
///
/// Delivered as `{"type":"stream","id":<subscription>,"body":{...}}` until the
/// client cancels or the connection closes.
#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(tag = "kind", rename_all = "snake_case")]
pub enum StreamItem {
    /// A line was appended to the activity log.
    Event { event: Box<Event> },
    /// Counters moved for one destination of one running job.
    Progress {
        run_id: Uuid,
        job_id: Uuid,
        destination_id: Uuid,
        status: RunStatus,
        progress: Box<Progress>,
    },
    /// The aggregate picture changed.
    Status { snapshot: Box<StatusSnapshot> },
    /// **Backpressure marker.** The subscriber did not read fast enough and
    /// the daemon dropped the oldest `missed` items rather than buffering them
    /// or stalling the engine that produces them.
    ///
    /// The correct reaction is not to try to recover the lost items — they are
    /// gone — but to resynchronise: issue `status` and redraw from the
    /// snapshot. A client that renders a log tail should show a gap marker.
    Lagged { missed: u64 },
}

impl StreamItem {
    /// The topic this item belongs to, used to filter per subscription.
    ///
    /// [`StreamItem::Lagged`] deliberately has no topic of its own: it is
    /// delivered to whichever subscription lagged, regardless of what that
    /// subscription asked for, because suppressing it would leave a client
    /// silently showing stale data.
    pub fn topic(&self) -> Option<Topic> {
        match self {
            StreamItem::Event { .. } => Some(Topic::Events),
            StreamItem::Progress { .. } => Some(Topic::Progress),
            StreamItem::Status { .. } => Some(Topic::Status),
            StreamItem::Lagged { .. } => None,
        }
    }

    /// True when a subscription for `topics` should receive this item.
    pub fn matches(&self, topics: &[Topic]) -> bool {
        match self.topic() {
            None => true,
            Some(t) => topics.contains(&t),
        }
    }

    fn sanitise(&mut self) {
        match self {
            StreamItem::Event { event } => {
                scrub_in_place(&mut event.message);
            }
            StreamItem::Progress { progress, .. } => {
                scrub_opt(&mut progress.current_path);
            }
            StreamItem::Status { snapshot } => {
                for run in &mut snapshot.active_runs {
                    sanitise_run(run);
                }
                for event in &mut snapshot.recent_events {
                    scrub_in_place(&mut event.message);
                }
            }
            StreamItem::Lagged { .. } => {}
        }
    }
}

fn sanitise_run(run: &mut JobRun) {
    for dest in &mut run.destinations {
        scrub_opt(&mut dest.progress.current_path);
        for warning in &mut dest.warnings {
            scrub_in_place(warning);
        }
        if let Some(err) = &mut dest.error {
            scrub_in_place(&mut err.message);
            scrub_opt(&mut err.hint);
            scrub_opt(&mut err.detail);
        }
    }
}

