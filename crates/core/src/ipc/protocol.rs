/// Correlates a response, and every item of a stream, with the request that
/// caused it.
///
/// Scoped to one connection. A `u64` rather than a UUID because it costs four
/// bytes on the wire instead of thirty-eight, is trivial to generate in any
/// language, and needs no uniqueness beyond one socket.
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash, Serialize, Deserialize)]
#[serde(transparent)]
pub struct RequestId(pub u64);

impl std::fmt::Display for RequestId {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        write!(f, "{}", self.0)
    }
}

/// Identity of the process on the other end of the socket, as far as the OS
/// will tell us.
///
/// This is diagnostic and audit information, **not** an authorisation
/// mechanism for anything that matters. The access control that matters is the
/// endpoint's DACL (Windows) or the socket's mode plus a `SO_PEERCRED` check
/// (unix), applied before a single byte is read. See
/// [`super::security`].
#[derive(Debug, Clone, Copy, Default, Serialize, Deserialize)]
pub struct PeerIdentity {
    /// Process id of the peer, when the platform reports one.
    pub pid: Option<u32>,
    /// Effective user id of the peer. Unix only; Windows reports `None`
    /// because the named pipe's DACL, not a uid comparison, is the control.
    pub uid: Option<u32>,
    /// True when the transport positively established that the peer runs as
    /// the same user as the daemon. False means "not proven", not "hostile" —
    /// on Windows it is always false, and the DACL is what keeps strangers
    /// out.
    pub same_user: bool,
}

/// Everything a [`Handler`] method knows about the caller.
///
/// Passed by reference to every handler method so that the daemon can attribute
/// an action in the event log ("job started by pid 4123") without the protocol
/// having to carry a self-reported, forgeable identity field.
#[derive(Debug, Clone)]
pub struct RequestContext {
    /// Monotonic id of the connection within this daemon process.
    pub connection: u64,
    /// The request's own id, for correlating log lines with the client's view.
    pub request_id: RequestId,
    /// Protocol version this client negotiated.
    pub protocol: u32,
    /// Who is calling, as far as the OS reports.
    pub peer: PeerIdentity,
}

impl RequestContext {
    /// A context for in-process use — tests, and any future in-daemon caller
    /// that wants to reuse the dispatcher without a socket.
    pub fn local() -> RequestContext {
        RequestContext {
            connection: 0,
            request_id: RequestId(0),
            protocol: PROTOCOL_VERSION,
            peer: PeerIdentity { pid: Some(std::process::id()), uid: None, same_user: true },
        }
    }
}

