/// Build one [`ParamSpec`], normalising the stringified Rust type into
/// something a client author can read.
fn param(name: &str, ty: &str, summary: &str) -> ParamSpec {
    let compact: String = ty.chars().filter(|c| !c.is_whitespace()).collect();
    let optional = compact.starts_with("Option<");
    let secret = compact.contains("SecretString");
    // `Box<T>` is a layout decision with no wire meaning; showing it would
    // only confuse a client author in another language.
    let display = match compact.strip_prefix("Box<").and_then(|r| r.strip_suffix('>')) {
        Some(inner) => inner.to_string(),
        None => compact,
    };
    ParamSpec {
        name: name.to_string(),
        ty: display,
        summary: summary.trim().to_string(),
        optional,
        secret,
    }
}

/// The full, machine-readable command surface.
///
/// Generated, never written by hand. `superbackup help --json` prints this,
/// and `{"cmd":"schema"}` returns it.
pub fn schema() -> Schema {
    schema_with_limits(&Limits::default())
}

/// The command surface as served by a daemon configured with `limits`.
///
/// The server calls this so that `Schema::limits` reports the caps that are
/// actually in force, not the compiled-in defaults. A client that trusts the
/// schema and is then disconnected for exceeding a limit the schema did not
/// mention would have every right to be annoyed.
pub fn schema_with_limits(limits: &Limits) -> Schema {
    Schema {
        protocol: PROTOCOL_VERSION,
        min_protocol: MIN_PROTOCOL_VERSION,
        version: crate::VERSION.to_string(),
        commands: commands(),
        replies: reply_specs(),
        error_codes: ERROR_CODES.iter().map(|c| (*c).to_string()).collect(),
        topics: vec![
            TopicSpec {
                name: "events".to_string(),
                summary: "Activity-log lines as they are written.".to_string(),
            },
            TopicSpec {
                name: "progress".to_string(),
                summary: "Byte and file counters for running jobs. High volume.".to_string(),
            },
            TopicSpec {
                name: "status".to_string(),
                summary: "A full status snapshot whenever the aggregate picture changes."
                    .to_string(),
            },
        ],
        limits: LimitsSpec {
            max_line_bytes: limits.max_line_bytes,
            max_requests_per_second: limits.max_requests_per_second,
            request_burst: limits.request_burst,
            max_connections: limits.max_connections,
            stream_buffer: limits.stream_buffer,
        },
    }
}

