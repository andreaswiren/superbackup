/// What to do when a restored file already exists at the target path.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum ConflictPolicy {
    /// Leave the existing file alone. The safe default: a restore should never
    /// destroy data the user did not ask it to destroy.
    #[default]
    Skip,
    /// Replace the existing file.
    Overwrite,
    /// Write the restored file next to the existing one with a suffix.
    KeepBoth,
    /// Abort the whole restore on the first collision.
    Fail,
}

