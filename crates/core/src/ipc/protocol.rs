/// A secret that arrives *from* a client — a passphrase, an access key.
///
/// Deserialising into this type rather than `String` is what keeps a
/// passphrase out of logs. The inner [`Secret`](crate::secret::Secret) zeroes
/// itself on drop and its `Debug` prints `Secret([redacted; N bytes])`, so
/// `format!("{request:?}")` — the thing a tracing span, a panic message or a
/// hasty `dbg!` actually does — cannot leak it. There is a test that asserts
/// exactly this.
///
/// ## What this does not fix, stated honestly
///
/// [`Request`] is an internally tagged enum, so serde buffers the object
/// before dispatching on `cmd`; the passphrase therefore exists briefly inside
/// serde's own buffer, and before that inside the socket read buffer. The read
/// buffer is zeroed by the transport after every frame
/// ([`super::codec`]); serde's is not reachable from here. That
/// residue is a deliberate, documented trade against a wire format that a
/// human can type. The mitigations that carry the weight are: the value never
/// lands in a `String` *field*, never appears in `Debug`, is never written to
/// the event log, and is never returned by any request.
///
/// ## Serialisation is one-directional
///
/// A client has to be able to *send* one, so [`Serialize`] has to be able to
/// emit the plaintext. It does so **only for a value this process built to
/// send**. A value that arrived over the wire — every passphrase the daemon
/// ever sees — refuses to serialise, so the "someone logs the request struct"
/// path is closed on the side where it would actually be a breach:
///
/// ```text
/// client: SecretString::from_string("…")  -> serialises  (this is the point)
/// daemon: deserialised from the socket    -> refuses     (nothing needs to)
/// ```
///
/// The direction is carried in the value rather than enforced by a wrapper
/// type, because [`Request`] is generated by a macro: hand-writing a
/// serialiser for one variant of a macro-generated tagged enum would
/// reintroduce exactly the drift that generating it exists to prevent.
///
/// Deliberately **not** `PartialEq`/`Eq`, matching [`crate::secret::Secret`]:
/// deriving them would make variable-time comparison the path of least
/// resistance on a value carrying a master passphrase. Use
/// [`SecretString::ct_eq`].
#[derive(Clone)]
pub struct SecretString {
    secret: crate::secret::Secret,
    /// True when this value was built locally in order to be sent. False when
    /// it came off the wire, in which case serialising it is a bug and is
    /// refused. See the type documentation.
    outbound: bool,
}

impl SecretString {
    /// Wrap an existing secret **for transmission**.
    ///
    /// The result serialises. Use this only when building a request to send;
    /// there is no constructor that makes a received secret serialisable,
    /// because nothing legitimate needs one.
    pub fn new(secret: crate::secret::Secret) -> Self {
        SecretString { secret, outbound: true }
    }

    /// Constant-time comparison. There is no `==` for this type on purpose.
    pub fn ct_eq(&self, other: &SecretString) -> bool {
        self.secret.ct_eq(&other.secret)
    }

    /// Build one from a string the caller already holds, for transmission.
    /// The caller's copy is consumed and zeroed.
    pub fn from_string(s: String) -> Self {
        SecretString::new(crate::secret::Secret::from_string(s))
    }

    /// Whether this value may be serialised — true only for one this process
    /// built to send.
    pub fn is_outbound(&self) -> bool {
        self.outbound
    }

    /// Unwrap into the core secret type, consuming the wrapper.
    pub fn into_secret(self) -> crate::secret::Secret {
        self.secret
    }

    /// Borrow the secret. Deliberately named to make call sites auditable.
    pub fn expose(&self) -> &crate::secret::Secret {
        &self.secret
    }
}

impl std::fmt::Debug for SecretString {
    /// Delegates to [`Secret`](crate::secret::Secret)'s redacting `Debug`.
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        std::fmt::Debug::fmt(&self.secret, f)
    }
}

impl Serialize for SecretString {
    fn serialize<S: Serializer>(&self, serializer: S) -> std::result::Result<S::Ok, S::Error> {
        if !self.outbound {
            // The daemon is trying to write out a secret a client sent it.
            // Nothing legitimate does that, so this is a bug being caught
            // rather than a case to support — and an error is the only outcome
            // that surfaces the bug instead of the passphrase.
            return Err(serde::ser::Error::custom(
                "refusing to serialise a secret that was received rather than \
                 constructed for sending",
            ));
        }
        match self.secret.expose_str() {
            Some(s) => serializer.serialize_str(s),
            // Non-UTF-8 key material cannot be a JSON string. Refusing is the
            // right outcome: silently emitting a lossy value would produce a
            // credential that does not work, diagnosed hours later.
            None => Err(serde::ser::Error::custom(
                "secret is not valid UTF-8 and cannot be sent as a JSON string",
            )),
        }
    }
}

impl<'de> Deserialize<'de> for SecretString {
    fn deserialize<D: Deserializer<'de>>(deserializer: D) -> std::result::Result<Self, D::Error> {
        struct SecretVisitor;

        impl Visitor<'_> for SecretVisitor {
            type Value = SecretString;

            fn expecting(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
                f.write_str("a string containing secret material")
            }

            fn visit_str<E: de::Error>(self, v: &str) -> std::result::Result<Self::Value, E> {
                // Borrowed from the parser's buffer: copy the bytes straight
                // into the zeroing buffer without an intermediate `String`.
                // `outbound: false` — this came off the wire, so writing it
                // back out is refused.
                Ok(SecretString { secret: crate::secret::Secret::from_str(v), outbound: false })
            }

            fn visit_string<E: de::Error>(self, v: String) -> std::result::Result<Self::Value, E> {
                // Owned: `from_string` takes the allocation over and zeroes
                // the caller's view of it.
                Ok(SecretString { secret: crate::secret::Secret::from_string(v), outbound: false })
            }
        }

        deserializer.deserialize_str(SecretVisitor)
    }
}

